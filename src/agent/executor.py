"""
Executor
--------
Execute Planner-generated actions through the ToolRegistry.

Responsibilities:
1. Register available tools.
2. Execute planner actions sequentially.
3. Normalize tool inputs when necessary.
4. Record every tool execution into agent_logs.
5. Update plan_trace with actual observations.
6. Persist task state before and after execution.
7. Mark task as completed or failed.
"""

from __future__ import annotations

import json
import time
import uuid
from datetime import datetime
from typing import Any

from src.tools.base import ToolRegistry
from src.tools.vision_tool import VisionTool
from src.tools.communication_tool import CommunicationTool
from src.tools.database_tool import DatabaseTool


class Executor:
    """
    Execute a structured plan generated by Planner.

    Executor only performs actions.
    It does not generate plans or make planning decisions.
    """

    def __init__(
        self,
        db_path: str = "data/drrm.db",
        registry: ToolRegistry | None = None,
    ):
        self.registry = registry or ToolRegistry()

        self._register_default_tools(db_path)

    # ================================================================
    # Tool registration
    # ================================================================

    def _register_default_tools(self, db_path: str) -> None:
        """Register the default P0 tools."""

        if not self.registry.has("vision_tool"):
            self.registry.register(
                VisionTool()
            )

        if not self.registry.has("communication_tool"):
            self.registry.register(
                CommunicationTool()
            )

        if not self.registry.has("database_tool"):
            self.registry.register(
                DatabaseTool(
                    db_path=db_path
                )
            )

    # ================================================================
    # Main execution
    # ================================================================

    def execute(
        self,
        plan: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Execute a Planner-generated plan.

        Parameters
        ----------
        plan:
            Structured plan dictionary.

        Returns
        -------
        dict
            Execution result.
        """

        # ------------------------------------------------------------
        # Validate plan
        # ------------------------------------------------------------

        if not isinstance(plan, dict):
            return {
                "ok": False,
                "status": "failed",
                "error": "plan must be a dictionary",
            }

        task_id = str(
            plan.get("task_id")
            or self._generate_task_id()
        )

        trigger_type = plan.get(
            "trigger_type"
        )

        trigger_event = plan.get(
            "trigger_event"
        ) or trigger_type

        person_id = plan.get(
            "person_id"
        )

        priority = plan.get(
            "priority"
        )

        actions = plan.get(
            "actions",
            [],
        )

        if not isinstance(actions, list):
            return {
                "ok": False,
                "task_id": task_id,
                "status": "failed",
                "error": "plan.actions must be a list",
            }

        created = (
            plan.get("created")
            or self._now()
        )

        # ------------------------------------------------------------
        # Prepare plan trace
        # ------------------------------------------------------------

        plan_trace = self._prepare_plan_trace(
            plan,
            actions,
        )

        # ------------------------------------------------------------
        # Save initial task
        # ------------------------------------------------------------

        initial_save = self._save_task(
            task_id=task_id,
            trigger_event=trigger_event,
            plan_trace=plan_trace,
            status="running",
            created=created,
            finished=None,
        )

        if not initial_save:
            print(
                "[Executor] Initial task save failed."
            )

            return {
                "ok": False,
                "task_id": task_id,
                "status": "failed",
                "error": "Failed to save initial task.",
                "plan_trace": plan_trace,
            }

        # ------------------------------------------------------------
        # Execute planner actions
        # ------------------------------------------------------------

        results: list[dict[str, Any]] = []

        actions_executed = 0

        execution_failed = False

        for index, action_item in enumerate(
            actions
        ):
            step_number = index + 1

            # --------------------------------------------------------
            # Validate action
            # --------------------------------------------------------

            if not isinstance(
                action_item,
                dict,
            ):
                result = {
                    "ok": False,
                    "error": (
                        "Action item must be a dictionary."
                    ),
                }

                self._update_plan_trace(
                    plan_trace,
                    step_number,
                    result,
                )

                results.append(result)

                execution_failed = True

                break

            tool_name = action_item.get(
                "tool"
            )

            action = action_item.get(
                "action"
            )

            tool_input = action_item.get(
                "input",
                {},
            )

            if not tool_name:
                result = {
                    "ok": False,
                    "error": "Missing tool name.",
                }

                self._update_plan_trace(
                    plan_trace,
                    step_number,
                    result,
                )

                results.append(result)

                execution_failed = True

                break

            if not action:
                result = {
                    "ok": False,
                    "error": "Missing action.",
                }

                self._update_plan_trace(
                    plan_trace,
                    step_number,
                    result,
                )

                results.append(result)

                execution_failed = True

                break

            if not isinstance(
                tool_input,
                dict,
            ):
                tool_input = {}

            # --------------------------------------------------------
            # Normalize input
            # --------------------------------------------------------

            normalized_input = (
                self._normalize_tool_input(
                    tool_name=tool_name,
                    action=action,
                    tool_input=tool_input,
                )
            )

            normalized_input[
                "action"
            ] = action

            # --------------------------------------------------------
            # Execute tool
            # --------------------------------------------------------

            start_time = time.perf_counter()

            try:
                result = self.registry.execute(
                    tool_name,
                    **normalized_input,
                )

                latency_ms = int(
                    (
                        time.perf_counter()
                        - start_time
                    )
                    * 1000
                )

            except Exception as exc:
                latency_ms = int(
                    (
                        time.perf_counter()
                        - start_time
                    )
                    * 1000
                )

                result = {
                    "ok": False,
                    "action": action,
                    "error": str(exc),
                }

            # --------------------------------------------------------
            # Normalize result
            # --------------------------------------------------------

            if isinstance(
                result,
                dict,
            ):
                result = dict(result)

                result.setdefault(
                    "tool",
                    tool_name,
                )

                result.setdefault(
                    "latency_ms",
                    latency_ms,
                )

            else:
                result = {
                    "ok": False,
                    "tool": tool_name,
                    "action": action,
                    "error": (
                        "Tool returned a non-dictionary result."
                    ),
                    "raw_result": result,
                    "latency_ms": latency_ms,
                }

            # --------------------------------------------------------
            # Update plan trace
            # --------------------------------------------------------

            self._update_plan_trace(
                plan_trace,
                step_number,
                result,
            )

            # --------------------------------------------------------
            # Save agent log
            # --------------------------------------------------------

            self._save_agent_log(
                task_id=task_id,
                tool_name=tool_name,
                tool_input=normalized_input,
                output=result,
                latency_ms=latency_ms,
            )

            results.append(result)

            actions_executed += 1

            # --------------------------------------------------------
            # Stop on failed action
            # --------------------------------------------------------

            if not result.get("ok"):
                execution_failed = True

                break

        # ============================================================
        # Finalize task
        # ============================================================

        finished = self._now()

        if execution_failed:
            final_status = "failed"
        else:
            final_status = "completed"

        # ------------------------------------------------------------
        # IMPORTANT:
        # Save the SAME task_id again.
        #
        # This updates the task record from:
        # running
        #
        # to:
        # completed / failed
        #
        # and writes the final plan_trace with observations.
        # ------------------------------------------------------------

        final_save = self._save_task(
            task_id=task_id,
            trigger_event=trigger_event,
            plan_trace=plan_trace,
            status=final_status,
            created=created,
            finished=finished,
        )

        if not final_save:
            print(
                "[Executor] Final task save failed."
            )

        # ------------------------------------------------------------
        # Return execution result
        # ------------------------------------------------------------

        return {
            "ok": (
                final_status == "completed"
                and final_save
            ),
            "task_id": task_id,
            "status": final_status,
            "trigger_type": trigger_type,
            "person_id": person_id,
            "priority": priority,
            "actions_total": len(actions),
            "actions_executed": actions_executed,
            "results": results,
            "plan_trace": plan_trace,
            "created": created,
            "finished": finished,
        }

    # ================================================================
    # Contract execution (schemas/agent_task.json)
    # ================================================================

    def execute_agent_task(
        self,
        task: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Execute one contract-conformant agent task.

        Contract format (docs/interface.md):

            {
                "task_id": ...,
                "trigger": {"source", "reason", "ts"},
                "actions": [{"tool": ..., "args": {...}}],
                "status": "pending"
            }

        Rules:
            1. The task is validated against
               schemas/agent_task.json first (B9).
            2. Empty actions are treated as a no-op:
               status -> done, nothing is persisted
               (interface.md fallback rule).
            3. Each action's dispatch key is args["action"].

        Returns:
            Execution result with contract status values
            (done / failed).
        """

        from src.agent.task_schema import (
            validate_agent_task,
        )

        # ------------------------------------------------------------
        # 1. Schema validation (B9)
        # ------------------------------------------------------------

        errors = validate_agent_task(task)

        if errors:

            return {
                "ok": False,
                "task_id": (
                    task.get("task_id")
                    if isinstance(task, dict)
                    else None
                ),
                "status": "failed",
                "stage": "schema_validation",
                "errors": errors,
            }

        # ------------------------------------------------------------
        # 2. Empty actions -> no-op
        # ------------------------------------------------------------

        actions = task["actions"]

        if len(actions) == 0:

            return {
                "ok": True,
                "task_id": task["task_id"],
                "status": "done",
                "actions_total": 0,
                "actions_executed": 0,
                "results": [],
                "note": (
                    "Empty actions: no-op, "
                    "nothing persisted."
                ),
            }

        # ------------------------------------------------------------
        # 3. Contract -> internal plan format
        # ------------------------------------------------------------

        trigger = task.get("trigger") or {}

        internal_actions: list[dict[str, Any]] = []

        for index, contract_action in enumerate(actions):

            tool_name = contract_action.get("tool")
            args = dict(
                contract_action.get("args") or {}
            )

            internal_actions.append(
                {
                    "step": index + 1,
                    "action": args.get(
                        "action",
                        tool_name,
                    ),
                    "tool": tool_name,
                    "input": args,
                    "reason": trigger.get("reason"),
                }
            )

        # ------------------------------------------------------------
        # 4. Person / priority for bookkeeping
        # ------------------------------------------------------------

        person_id = None
        priority = None

        for contract_action in actions:

            args = contract_action.get("args") or {}

            if person_id is None:
                person_id = args.get("person_id")

            if priority is None:
                priority = args.get(
                    "priority"
                ) or args.get("severity")

        internal_plan = {
            "task_id": task["task_id"],
            "trigger_type": "LLM_PROPOSAL",
            "trigger_event": trigger.get(
                "reason"
            ),
            "person_id": person_id,
            "priority": priority,
            "created": task.get("created")
            or trigger.get("ts")
            or self._now(),
            "actions": internal_actions,
            "source": "llm",
            "event_summary": task.get(
                "event_summary"
            ),
        }

        # ------------------------------------------------------------
        # 5. Execute through the standard pipeline
        # ------------------------------------------------------------

        execution_result = self.execute(
            internal_plan
        )

        # ------------------------------------------------------------
        # 6. Map internal status -> contract status
        # ------------------------------------------------------------

        status = execution_result.get("status")

        contract_status = (
            "done"
            if status == "completed"
            else "failed"
        )

        return {
            "ok": execution_result.get("ok", False),
            "task_id": execution_result.get(
                "task_id"
            ),
            "status": contract_status,
            "actions_total": execution_result.get(
                "actions_total"
            ),
            "actions_executed": execution_result.get(
                "actions_executed"
            ),
            "results": execution_result.get(
                "results"
            ),
            "plan_trace": execution_result.get(
                "plan_trace"
            ),
            "execution": execution_result,
        }

    # ================================================================
    # Tool input normalization
    # ================================================================

    def _normalize_tool_input(
        self,
        tool_name: str,
        action: str,
        tool_input: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Normalize Planner input for the target Tool.

        CommunicationTool uses:
            severity

        Planner commonly uses:
            priority
        """

        normalized = dict(
            tool_input
        )

        if (
            tool_name
            == "communication_tool"
            and action
            == "send_alert"
        ):
            # Planner -> CommunicationTool
            if "severity" not in normalized:
                normalized[
                    "severity"
                ] = normalized.get(
                    "priority",
                    "HIGH",
                )

            # Preserve state and risk information.
            extra = dict(
                normalized.get(
                    "extra"
                )
                or {}
            )

            if "state" in normalized:
                extra.setdefault(
                    "state",
                    normalized["state"],
                )

            if "risk_score" in normalized:
                extra.setdefault(
                    "risk_score",
                    normalized["risk_score"],
                )

            normalized[
                "extra"
            ] = extra

        return normalized

    # ================================================================
    # Database task persistence
    # ================================================================

    def _save_task(
        self,
        task_id: str,
        trigger_event: Any,
        plan_trace: list[dict[str, Any]],
        status: str,
        created: str,
        finished: str | None,
    ) -> bool:
        """
        Save or update a task through DatabaseTool.

        The same task_id is intentionally saved twice:

        First:
            status = running

        Finally:
            status = completed / failed
        """

        task = {
            "task_id": task_id,
            "trigger_event": trigger_event,
            "plan_trace": plan_trace,
            "status": status,
            "created": created,
            "finished": finished,
        }

        try:
            result = self.registry.execute(
                "database_tool",
                action="save_task",
                task=task,
            )

            print(
                "[Executor] save_task result:"
            )

            print(
                json.dumps(
                    result,
                    indent=2,
                    ensure_ascii=False,
                    default=str,
                )
            )

            if not isinstance(
                result,
                dict,
            ):
                return False

            if result.get("ok"):
                return True

            print(
                "[Executor] save_task returned ok=False."
            )

            return False

        except Exception as exc:
            import traceback

            print(
                "[Executor] Exception while saving task:"
            )

            print(
                str(exc)
            )

            traceback.print_exc()

            return False

    # ================================================================
    # Agent log persistence
    # ================================================================

    def _save_agent_log(
        self,
        task_id: str,
        tool_name: str,
        tool_input: dict[str, Any],
        output: dict[str, Any],
        latency_ms: int,
    ) -> None:
        """
        Save one tool execution into agent_logs.
        """

        try:
            result = self.registry.execute(
                "database_tool",
                action="save_agent_log",
                task_id=task_id,
                logged_tool_name=tool_name,
                input=tool_input,
                output=output,
                latency_ms=latency_ms,
            )

            if isinstance(
                result,
                dict,
            ) and not result.get("ok"):
                print(
                    "[Executor] Warning:"
                    " save_agent_log returned ok=False."
                )

        except Exception as exc:
            import traceback

            print(
                "[Executor] Warning:"
                f" failed to save agent log: {exc}"
            )

            traceback.print_exc()

    # ================================================================
    # Plan trace
    # ================================================================

    def _prepare_plan_trace(
        self,
        plan: dict[str, Any],
        actions: list[dict[str, Any]],
    ) -> list[dict[str, Any]]:
        """
        Prepare plan_trace.

        Every action receives an observation field.
        """

        existing_trace = plan.get(
            "plan_trace"
        )

        trace: list[dict[str, Any]] = []

        if isinstance(
            existing_trace,
            list,
        ):
            for index, step in enumerate(
                existing_trace
            ):
                if isinstance(
                    step,
                    dict,
                ):
                    item = dict(step)
                else:
                    item = {}

                item.setdefault(
                    "step",
                    index + 1,
                )

                item.setdefault(
                    "observation",
                    None,
                )

                trace.append(item)

        # Make sure every action has a trace entry.
        while len(trace) < len(actions):
            index = len(trace)

            action_item = actions[
                index
            ]

            if isinstance(
                action_item,
                dict,
            ):
                tool = action_item.get(
                    "tool",
                    "",
                )

                action = action_item.get(
                    "action",
                    "",
                )

                input_data = action_item.get(
                    "input",
                    {},
                )

                thought = action_item.get(
                    "thought",
                    "",
                )

                action_name = (
                    f"{tool}.{action}"
                    if tool and action
                    else str(
                        action or tool
                    )
                )

            else:
                action_name = ""
                input_data = {}
                thought = ""

            trace.append(
                {
                    "step": index + 1,
                    "thought": thought,
                    "action": action_name,
                    "input": input_data,
                    "observation": None,
                }
            )

        # Keep trace length aligned with actions.
        if len(trace) > len(actions):
            trace = trace[
                : len(actions)
            ]

        return trace

    def _update_plan_trace(
        self,
        plan_trace: list[dict[str, Any]],
        step_number: int,
        observation: dict[str, Any],
    ) -> None:
        """
        Write actual Tool output into plan_trace.
        """

        index = step_number - 1

        if (
            index < 0
            or index >= len(plan_trace)
        ):
            return

        plan_trace[
            index
        ]["observation"] = observation

    # ================================================================
    # Utility
    # ================================================================

    @staticmethod
    def _now() -> str:
        """Return current timestamp."""

        return datetime.now().isoformat()

    @staticmethod
    def _generate_task_id() -> str:
        """Generate fallback task ID."""

        return (
            "T-"
            + datetime.now().strftime(
                "%Y%m%d"
            )
            + "-"
            + uuid.uuid4().hex[
                :8
            ].upper()
        )


